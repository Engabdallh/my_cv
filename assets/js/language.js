function normalizeText(value) {
  return value.replace(/\s+/g, " ").trim();
}

function translateTextNode(node, language) {
  const originalText = normalizeText(node.nodeValue);

  if (!originalText) return;

  if (language === "ar") {
    if (translations[originalText]) {
      node.nodeValue = node.nodeValue.replace(
        node.nodeValue.trim(),
        translations[originalText]
      );
    }
    return;
  }

  const englishText = Object.keys(translations).find(
    key => translations[key] === originalText
  );

  if (englishText) {
    node.nodeValue = node.nodeValue.replace(
      node.nodeValue.trim(),
      englishText
    );
  }
}

function translatePage(language) {
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (!node.nodeValue.trim()) {
          return NodeFilter.FILTER_REJECT;
        }

        const parent = node.parentElement;

        if (!parent) return NodeFilter.FILTER_REJECT;

        const excludedTags = [
          "SCRIPT",
          "STYLE",
          "NOSCRIPT",
          "CODE",
          "PRE"
        ];

        if (excludedTags.includes(parent.tagName)) {
          return NodeFilter.FILTER_REJECT;
        }

        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  let node;

  while ((node = walker.nextNode())) {
    translateTextNode(node, language);
  }

  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  const languageButton = document.getElementById("language-toggle");

  if (languageButton) {
    languageButton.textContent = languageButtonLabels[language];
  }

  const typedElement = document.querySelector(".typed");

  if (typedElement) {
    typedElement.setAttribute(
      "data-typed-items",
      typedRoles[language].join(", ")
    );
  }

  document.dispatchEvent(
    new CustomEvent("languageChanged", {
      detail: { language }
    })
  );

  try {
    localStorage.setItem("preferredLanguage", language);
  } catch (error) {
    console.warn("Unable to save language preference:", error);
  }
}

